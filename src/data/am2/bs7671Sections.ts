/** "411.3.3" → "Protective measure: automatic disconnection of supply". */
export function sectionTitle(regNumber: string): string | null {
  return BS7671_SECTIONS[regNumber.split('.')[0]] ?? null;
}

/** "411.3.3" → "Part 4 › Chapter 41 › Section 411". */
export function bookPath(regNumber: string): string {
  const sec = regNumber.split('.')[0];
  return `Part ${sec[0]} › Chapter ${sec.slice(0, 2)} › Section ${sec}`;
}
