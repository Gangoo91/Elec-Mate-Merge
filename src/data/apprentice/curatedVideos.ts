/** Resolve a path's ids to videos, silently dropping any that vanish. */
export function getPathVideos(path: LearningPath): CuratedVideo[] {
  return path.videoIds
    .map((id) => curatedVideos.find((v) => v.id === id))
    .filter((v): v is CuratedVideo => Boolean(v));
}
