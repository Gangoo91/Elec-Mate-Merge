#!/usr/bin/env node
/**
 * sync-edge-bs7671-data — copies the verified BS 7671 Appendix 4 data from
 * src/lib/calculators/bs7671-data/ into supabase/functions/_shared/bs7671-appendix4/
 * so edge functions (Elec-AI's select_cable_size tool) use the SAME numbers as
 * the in-app calculators.
 *
 * The src files are the source of truth (transcribed from the printed standard,
 * ELE-1256/1257). Never edit the copies — edit src and re-run this.
 *
 * The only transform is adding `.ts` to relative imports, which Deno requires.
 *
 *   node scripts/sync-edge-bs7671-data.mjs           write the copies
 *   node scripts/sync-edge-bs7671-data.mjs --check   exit 1 if a copy has drifted
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src/lib/calculators/bs7671-data');
// NOT _shared/bs7671-data/ — that folder holds older, hand-maintained copies
// that other functions import with a different API.
const DEST = join(ROOT, 'supabase/functions/_shared/bs7671-appendix4');

const FILES = [
  'appendix4CurrentCapacity.ts',
  'cableCapacities.ts',
  'temperatureFactors.ts',
  'thermalInsulationFactors.ts',
  'voltageDropTables.ts',
];

const HEADER =
  '// GENERATED by scripts/sync-edge-bs7671-data.mjs from src/lib/calculators/bs7671-data/.\n' +
  '// Do not edit — change the src file and re-run the script.\n\n';

const render = (name) =>
  HEADER +
  readFileSync(join(SRC, name), 'utf8').replace(
    /(from\s+['"])(\.\/[^'"]+?)(['"])/g,
    (m, a, path, b) => (path.endsWith('.ts') ? m : `${a}${path}.ts${b}`)
  );

const check = process.argv.includes('--check');
let drift = 0;
if (!check) mkdirSync(DEST, { recursive: true });

for (const name of FILES) {
  const want = render(name);
  const target = join(DEST, name);
  if (check) {
    const have = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (have !== want) {
      drift++;
      console.error(`✗ ${name}: edge copy ${have === null ? 'missing' : 'differs from src'}`);
    }
  } else {
    writeFileSync(target, want);
    console.log(`✓ ${name}`);
  }
}

if (check) {
  if (drift) {
    console.error(`\n${drift} file(s) out of sync — run: node scripts/sync-edge-bs7671-data.mjs`);
    process.exit(1);
  }
  console.log(`✓ ${FILES.length} BS 7671 data files in sync with src`);
}
