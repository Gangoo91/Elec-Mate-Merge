#!/usr/bin/env node
/**
 * generate-mock-exam-sitemap — rebuilds public/sitemap-mock-exams.xml from the
 * routes and the topic registry, instead of it being hand-maintained.
 *
 * WHY THIS EXISTS
 * The file was static and last written 2026-07-17. It listed 72 topic landings
 * because that was the count on the day someone typed them in. Every topic page
 * added since would have been missing from the sitemap — discoverable only by
 * crawling the "Practice by topic" strip, rather than declared outright.
 *
 * Sources of truth:
 *   • parent exams  — path="…" literals in src/routes/MockExamRoutes.tsx
 *   • topic pages   — getAllTopicRoutes() in the topic registry
 *
 * `lastmod` is PRESERVED for URLs already in the file. A sitemap that stamps
 * today's date on every URL each time it is regenerated is telling Google that
 * 170 pages changed when none did, which devalues the signal for the pages
 * that genuinely did change.
 *
 * Usage: npm run build:sitemap:mock-exams
 */
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'fs';
import { join, dirname } from 'path';
import { tmpdir } from 'os';
import { fileURLToPath } from 'url';
import { execFileSync } from 'child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public/sitemap-mock-exams.xml');
const BASE = 'https://www.elec-mate.com';
const TODAY = new Date().toISOString().slice(0, 10);

/** Parent exam slugs from the route file, minus the dynamic topic route. */
function parentExams() {
  const src = readFileSync(join(ROOT, 'src/routes/MockExamRoutes.tsx'), 'utf-8');
  return [...src.matchAll(/path="([^"]+)"/g)]
    .map((m) => m[1])
    .filter((p) => !p.includes(':') && p !== '*')
    .map((p) => p.replace(/^\/+/, ''))
    .filter(Boolean)
    .sort();
}

/** Topic landings, straight from the registry that renders them. */
function topicRoutes() {
  const dir = mkdtempSync(join(tmpdir(), 'sitemap-'));
  try {
    const entry = join(dir, 'probe.ts');
    const bundle = join(dir, 'probe.cjs');
    writeFileSync(
      entry,
      `import { getAllTopicRoutes } from '@/components/seo/mockExamTopicRegistry';\n` +
        `console.log(JSON.stringify(getAllTopicRoutes().map(r => r.examSlug + '/' + r.topicSlug).sort()));\n`
    );
    execFileSync(
      'npx',
      ['esbuild', entry, '--bundle', '--platform=node', '--format=cjs',
       `--alias:@=${join(ROOT, 'src')}`, `--outfile=${bundle}`, '--log-level=error'],
      { cwd: ROOT, stdio: ['ignore', 'ignore', 'inherit'] }
    );
    return JSON.parse(execFileSync('node', [bundle], { encoding: 'utf-8' }));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Existing lastmod per URL, so unchanged pages keep their date. */
function existingLastmod() {
  const map = new Map();
  let xml = '';
  try {
    xml = readFileSync(OUT, 'utf-8');
  } catch {
    return map; // first run
  }
  for (const m of xml.matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) {
    map.set(m[1].trim(), m[2].trim());
  }
  return map;
}

const prev = existingLastmod();
const url = (path, priority) => {
  const loc = `${BASE}${path}`;
  const lastmod = prev.get(loc) ?? TODAY;
  return `  <url><loc>${loc}</loc><lastmod>${lastmod}</lastmod><changefreq>weekly</changefreq><priority>${priority}</priority></url>`;
};

const exams = parentExams();
const topics = topicRoutes();

const body = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
  '        xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
  '        xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9',
  '        http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd">',
  `  <!-- GENERATED by scripts/generate-mock-exam-sitemap.mjs — do not hand-edit.`,
  `       ${exams.length} exams + ${topics.length} topic landings + 1 hub. -->`,
  url('/mock-exams', '0.9'),
  '',
  '  <!-- Exams -->',
  ...exams.map((s) => url(`/mock-exams/${s}`, '0.8')),
  '',
  '  <!-- Topic landings -->',
  ...topics.map((t) => url(`/mock-exams/${t}`, '0.7')),
  '</urlset>',
  '',
].join('\n');

const added = [...exams.map((s) => `/mock-exams/${s}`), ...topics.map((t) => `/mock-exams/${t}`)]
  .filter((p) => !prev.has(`${BASE}${p}`)).length;

writeFileSync(OUT, body);
console.log(
  `sitemap-mock-exams.xml: ${exams.length + topics.length + 1} URLs ` +
    `(${exams.length} exams, ${topics.length} topics) — ${added} new, ${prev.size} kept their lastmod`
);
