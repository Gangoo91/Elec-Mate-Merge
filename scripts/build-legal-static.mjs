#!/usr/bin/env node
/**
 * Builds public/privacy.html and public/account-deletion.html from the same
 * Markdown the app renders (src/content/legal/*.md).
 *
 * Why static copies exist: Google Play and App Store reviewers load these URLs
 * without JavaScript, and Vercel serves public/*.html ahead of the SPA. Until
 * 4 Oct 2026 the static privacy page was a hand-written copy that had drifted
 * from the app's version (different processors, retention, contacts). Now
 * there's one source.
 *
 *   node scripts/build-legal-static.mjs          # write the files
 *   node scripts/build-legal-static.mjs --check  # CI: fail if they're stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

const DOCS = [
  { src: 'src/content/legal/privacy.md', out: 'public/privacy.html', path: '/privacy' },
  {
    src: 'src/content/legal/account-deletion.md',
    out: 'public/account-deletion.html',
    path: '/account-deletion',
  },
];

// Mirrors src/content/legal/parse.ts
const slugify = (text) =>
  text
    .toLowerCase()
    .replace(/[’'`]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

function parse(source) {
  const m = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  const meta = {};
  for (const line of (m ? m[1] : '').split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { ...meta, body: (m ? m[2] : source).trim() };
}

const textOf = (c) =>
  Array.isArray(c) ? c.map(textOf).join('') : typeof c === 'string' ? c : c?.props ? textOf(c.props.children) : '';

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

const CSS = `
:root{color-scheme:dark}*{box-sizing:border-box}
body{margin:0;background:#1c1c1c;color:#fff;font:16px/1.7 -apple-system,BlinkMacSystemFont,"Segoe UI",Inter,Roboto,sans-serif}
main{max-width:46rem;margin:0 auto;padding:40px 20px 64px}
.eyebrow{font-size:12px;font-weight:600;letter-spacing:.16em;text-transform:uppercase;color:#ffc800;margin:0}
h1{font-size:36px;line-height:1.05;letter-spacing:-.03em;margin:12px 0 0}
.summary{font-size:17px;margin:16px 0 0}.updated{font-size:13.5px;margin:12px 0 32px}.updated b{color:#ffc800}
h2{font-size:22px;line-height:1.2;margin:48px 0 0;padding-top:32px;border-top:1px solid rgba(255,255,255,.08)}
h2:first-of-type{border-top:0;padding-top:0;margin-top:0}
p,ul,ol{margin:16px 0 0}li{margin:6px 0}li::marker{color:#ffc800}
a{color:#ffc800;font-weight:600}code{background:rgba(255,255,255,.08);padding:1px 6px;border-radius:4px;font-size:14px}
table{width:100%;border-collapse:collapse;margin:20px 0 0;font-size:14.5px;line-height:1.4}
th{text-align:left;font-size:12px;letter-spacing:.08em;text-transform:uppercase;padding:8px 12px 8px 0;border-bottom:1px solid rgba(255,200,0,.5)}
td{padding:12px 12px 12px 0;vertical-align:top;border-bottom:1px solid rgba(255,255,255,.08)}
footer{margin-top:56px;padding-top:24px;border-top:1px solid rgba(255,255,255,.08);font-size:13.5px}
@media (max-width:560px){table,thead,tbody,tr,td{display:block}thead{display:none}tr{padding:12px 0;border-bottom:1px solid rgba(255,255,255,.08)}td{border:0;padding:2px 0}td:first-child{font-weight:600;font-size:16px}}
`;

function render(doc) {
  const html = renderToStaticMarkup(
    createElement(ReactMarkdown, {
      remarkPlugins: [remarkGfm],
      components: {
        h2: ({ children }) => createElement('h2', { id: slugify(textOf(children)) }, children),
        a: ({ href, children }) =>
          createElement(
            'a',
            {
              href: href?.startsWith('/') ? `https://www.elec-mate.com${href}` : href,
              ...(href?.startsWith('/') ? {} : { rel: 'noopener noreferrer' }),
            },
            children
          ),
      },
      children: doc.body,
    })
  );
  return `<!doctype html>
<!-- GENERATED by scripts/build-legal-static.mjs from ${doc.src}. Edit the Markdown, then re-run. -->
<html lang="en-GB">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>${esc(doc.title)} · Elec-Mate Ltd</title>
<meta name="description" content="${esc(doc.summary)}">
<link rel="canonical" href="https://www.elec-mate.com${doc.path}">
<style>${CSS}</style>
</head>
<body>
<main>
<p class="eyebrow">Legal · Elec-Mate Ltd</p>
<h1>${esc(doc.title)}</h1>
<p class="summary">${esc(doc.summary)}</p>
<p class="updated">Last updated <b>${esc(doc.updated)}</b></p>
${html}
<footer>Elec-Mate Ltd · company number 16416291 · registered office 33 Gable Road, Whitehaven, CA28 8HE · ICO registration ZB935897 · <a href="mailto:info@elec-mate.com">info@elec-mate.com</a> · <a href="https://www.elec-mate.com">www.elec-mate.com</a></footer>
</main>
</body>
</html>
`;
}

const check = process.argv.includes('--check');
let stale = 0;
for (const d of DOCS) {
  const doc = { ...parse(readFileSync(d.src, 'utf8')), src: d.src, path: d.path };
  const out = render(doc);
  if (check) {
    let current = '';
    try {
      current = readFileSync(d.out, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== out) {
      console.error(`✗ ${d.out} is out of date — run: node scripts/build-legal-static.mjs`);
      stale++;
    } else console.log(`✓ ${d.out}`);
  } else {
    writeFileSync(d.out, out);
    console.log(`wrote ${d.out}`);
  }
}
process.exit(stale ? 1 : 0);
