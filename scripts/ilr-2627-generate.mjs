#!/usr/bin/env node
/**
 * ELE-2087. Regenerates the two TypeScript modules the college-ilr-return edge
 * function imports from the official ILR 2026/27 files stored beside them:
 *
 *   ILR-2026-27-schemafile-January.xsd   -> schema.ts      (the XSD as a string + SHA-256)
 *   ILR-validation-rules-2627-v4.csv     -> rules-meta.ts  (every published rule: id,
 *                                                           severity, status, category,
 *                                                           official error message)
 *
 * Edge functions are bundled from imports, so the XSD travels as a module. The
 * .xsd and .csv files are the source of truth; never edit the generated files.
 *
 *   node scripts/ilr-2627-generate.mjs          write the modules
 *   node scripts/ilr-2627-generate.mjs --check  exit 1 if they are out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const DIR = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  '../supabase/functions/_shared/ilr/2627'
);
const XSD = 'ILR-2026-27-schemafile-January.xsd';
const CSV = 'ILR-validation-rules-2627-v4.csv';

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',') {
      row.push(cell);
      cell = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell);
      rows.push(row);
      row = [];
      cell = '';
    } else cell += c;
  }
  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows;
}

const xsdText = fs.readFileSync(path.join(DIR, XSD), 'utf8');
const xsdSha = crypto
  .createHash('sha256')
  .update(fs.readFileSync(path.join(DIR, XSD)))
  .digest('hex');
const csvBuf = fs.readFileSync(path.join(DIR, CSV));
const csvSha = crypto.createHash('sha256').update(csvBuf).digest('hex');
const rows = parseCsv(csvBuf.toString('utf8').replace(/^﻿/, ''));
const head = rows[0];
const col = (n) => head.indexOf(n);
const rules = rows
  .slice(1)
  .filter((r) => r.length >= head.length && r[col('Name')])
  .map((r) => ({
    id: r[col('Name')].trim(),
    severity: r[col('Severity')].trim(),
    status: r[col('Status')].trim(),
    category: r[col('Category')].trim(),
    message: r[col('ErrorMessage')].replace(/\s+/g, ' ').trim(),
    // "Learner.ULN" style references to the fields the rule reads.
    fields: r[col('FieldValues')]
      .split(/[,\s]+/)
      .map((f) => f.trim())
      .filter((f) => /^[A-Za-z]+\.[A-Za-z0-9]+$/.test(f)),
  }));

const header = (src, sha) =>
  `// GENERATED by scripts/ilr-2627-generate.mjs from ${src} (SHA-256 ${sha}).\n// Do not edit by hand: change the source file and run the script.\n`;

const schemaTs =
  header(XSD, xsdSha) +
  `export const ILR_2627_XSD_FILE = ${JSON.stringify(XSD)};\n` +
  `export const ILR_2627_XSD_SHA256 = ${JSON.stringify(xsdSha)};\n` +
  `export const ILR_2627_XSD = ${JSON.stringify(xsdText)};\n`;

const metaTs =
  header(CSV, csvSha) +
  `export interface PublishedRule {\n  id: string;\n  severity: 'Error' | 'Warning' | 'N/A';\n  status: 'Active' | 'New' | 'Changed' | 'Deleted';\n  category: string;\n  message: string;\n  /** Entity.Field references the rule reads, from the FieldValues column. */\n  fields: string[];\n}\n` +
  `export const ILR_2627_RULES_FILE = ${JSON.stringify(CSV)};\n` +
  `export const ILR_2627_RULES_SHA256 = ${JSON.stringify(csvSha)};\n` +
  `export const ILR_2627_RULES_VERSION = 'Version 4 (published 10 Sep 2026)';\n` +
  `export const PUBLISHED_RULES: PublishedRule[] = ${JSON.stringify(rules, null, 0).replace(/\},\{/g, '},\n  {')};\n`;

const out = [
  ['schema.ts', schemaTs],
  ['rules-meta.ts', metaTs],
];
if (process.argv.includes('--check')) {
  let stale = false;
  for (const [f, body] of out) {
    const cur = fs.existsSync(path.join(DIR, f)) ? fs.readFileSync(path.join(DIR, f), 'utf8') : '';
    if (cur !== body) {
      console.error(`${f} is out of date: run node scripts/ilr-2627-generate.mjs`);
      stale = true;
    }
  }
  process.exit(stale ? 1 : 0);
}
for (const [f, body] of out) fs.writeFileSync(path.join(DIR, f), body);
console.log(
  `schema.ts (${xsdText.length} chars) and rules-meta.ts (${rules.length} rules) written.`
);
